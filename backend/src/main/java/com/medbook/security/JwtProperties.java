package com.medbook.security;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * Configuration for JWT issuing, injected from the environment — never from a
 * committed file.
 *
 * <p>Resolution order (first non-empty value wins):</p>
 * <ol>
 * <li>{@code medbook.security.jwt.secret} / {@code medbook.security.jwt.expiration-minutes}
 *     from any Spring property source,</li>
 * <li>the {@code JWT_SECRET} / {@code JWT_EXPIRATION_MINUTES} environment variables,</li>
 * <li>an empty secret and a 60-minute expiration as the final fallback.</li>
 * </ol>
 *
 * <p>{@code application.properties} deliberately contains <em>no</em> JWT settings: a
 * committed file must never carry a signing secret. When no secret is configured,
 * {@link SecurityConfig} generates an ephemeral development secret and logs a warning —
 * tokens simply stop being valid after a restart in that mode.</p>
 */
@Component
public class JwtProperties {

    /**
     * HMAC secret material. May be blank, in which case an ephemeral development key is
     * generated by {@link SecurityConfig}.
     */
    private final String secret;

    /** Token lifetime in minutes. */
    private final long expirationMinutes;

    public JwtProperties(
            @Value("${medbook.security.jwt.secret:${JWT_SECRET:}}") String secret,
            @Value("${medbook.security.jwt.expiration-minutes:${JWT_EXPIRATION_MINUTES:60}}") long expirationMinutes
    ) {
        this.secret = secret;
        this.expirationMinutes = expirationMinutes;
    }

    public String getSecret() {
        return secret;
    }

    public long getExpirationMinutes() {
        return expirationMinutes;
    }
}
